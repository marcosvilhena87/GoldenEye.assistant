#!/usr/bin/env python3
"""Export one GoldenEye.mapping ROM catalog as an inert Lua table. No offsets invented."""
import argparse
import json
import re
import subprocess
from pathlib import Path

ROM_ID = re.compile(r"^[A-Za-z0-9_.-]+$")
SHA256 = re.compile(r"^[0-9a-fA-F]{64}$")

def lua(value):
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return '"' + ''.join('\\%03d' % ord(c) if ord(c) < 32 or c in '"\\' else c for c in value) + '"'
    if isinstance(value, list):
        return "{" + ",".join(lua(x) for x in value) + "}"
    if isinstance(value, dict):
        return "{" + ",".join("[" + lua(str(k)) + "]=" + lua(v) for k, v in sorted(value.items())) + "}"
    raise TypeError(type(value))

def export(mapping: Path, rom_id: str):
    if not ROM_ID.fullmatch(rom_id):
        raise ValueError("invalid ROM id")
    catalog = mapping / "catalog"
    roms = json.loads((catalog / "roms.json").read_text(encoding="utf-8"))
    matches = [x for x in roms if x.get("id") == rom_id]
    if len(matches) != 1 or not SHA256.fullmatch(matches[0].get("sha256", "")):
        raise ValueError("ROM id missing/ambiguous or invalid SHA-256")
    symbols = json.loads((catalog / "symbols.json").read_text(encoding="utf-8"))
    selected = [s for s in symbols if s.get("rom_id") == rom_id]
    # Fail closed: experimental candidates are never exported as operational Lua symbols.
    if len({s["id"] for s in selected}) != len(selected):
        raise ValueError("duplicate symbol id")
    selected = [s for s in selected if s.get("status") == "validated"]
    revision = subprocess.run(
        ["git", "-C", str(mapping), "rev-parse", "HEAD"],
        capture_output=True, text=True, check=True
    ).stdout.strip()
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("invalid mapping commit")
    return {"rom_id": rom_id, "sha256": matches[0]["sha256"].lower(),
            "mapping_commit": revision, "symbols": selected}

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("mapping", type=Path)
    p.add_argument("--rom-id", required=True)
    p.add_argument("--output", type=Path, default=Path("config/mapping_snapshot.lua"))
    args = p.parse_args()
    result = export(args.mapping, args.rom_id)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("-- Generated by tools/export_mapping.py; do not edit.\nreturn " + lua(result) + "\n", encoding="utf-8")
    print("Exported", len(result["symbols"]), "symbols from mapping", result["mapping_commit"])

if __name__ == "__main__":
    main()
